WORKSPACE_ROOT = Path(__file__).resolve().parent.parent


def sanitize_run_name(raw_name: str | None) -> str | None:
    """Sanitize a user-provided run name for safe directory and .zip filenames."""
    if raw_name is None:
        return None
    cleaned = raw_name.strip()
    if not cleaned:
        return None
    if cleaned.lower().endswith(".zip"):
        cleaned = cleaned[:-4].strip()
    # Replace whitespace with hyphens and strip unsafe path/header characters
    cleaned = re.sub(r"\s+", "-", cleaned)
    cleaned = re.sub(r"[^A-Za-z0-9._-]+", "_", cleaned)
    cleaned = cleaned.strip("._-")
    if not cleaned:
        raise ValueError(
            "Run name must contain at least one alphanumeric character."
        )
    return cleaned[:120]


def list_artifact_files(artifact_dir: Path) -> list[dict[str, Any]]:
    """List downloadable artifact files generated by a benchmark run."""
    if not artifact_dir.exists() or not artifact_dir.is_dir():
        return []

    items: list[dict[str, Any]] = []
    for path in sorted(artifact_dir.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(artifact_dir).as_posix()
        items.append(
            {
                "name": rel,
                "size_bytes": path.stat().st_size,
            }
        )
    return items


@dataclass
class BenchmarkJob:
    """State and verbatim output buffer for a single AIPerf execution."""

    run_id: str
    run_name: str
    created_at: str
    principal: PrincipalInfo
    parsed_cmd: ParsedAIPerfCommand
    auth_mode: str  # "direct" | "proxy"
    artifact_dir: Path
    status: str = "starting"  # starting | running | succeeded | failed | cancelled
    return_code: int | None = None
    finished_at: str | None = None
    error_message: str | None = None
    logs: list[str] = field(default_factory=list)
    artifacts: list[dict[str, Any]] = field(default_factory=list)
    _subscribers: set[asyncio.Queue[dict[str, Any] | None]] = field(
        default_factory=set, repr=False
    )
    _process: asyncio.subprocess.Process | None = field(default=None, repr=False)
    _stop_requested: bool = field(default=False, repr=False)

    @property
    def zip_filename(self) -> str:
        return f"{self.run_name}.zip"

    def append_log(
        self, line: str, secrets_to_scrub: list[str | None] | None = None
    ) -> None:
        if secrets_to_scrub:
            for secret in secrets_to_scrub:
                if secret and len(secret) >= 8:
                    line = line.replace(secret, "<redacted>")
        self.logs.append(line)
        event = {"type": "log", "line": line}
        for q in list(self._subscribers):
            q.put_nowait(event)

    def broadcast_status(self) -> None:
        event = {"type": "status", "job": self.to_dict(include_logs=False)}
        for q in list(self._subscribers):
            q.put_nowait(event)

    def close_subscribers(self) -> None:
        for q in list(self._subscribers):
            q.put_nowait(None)
        self._subscribers.clear()

    def to_dict(self, *, include_logs: bool = False) -> dict[str, Any]:
        payload: dict[str, Any] = {
            "run_id": self.run_id,
            "run_name": self.run_name,
            "zip_filename": self.zip_filename,
            "created_at": self.created_at,
            "finished_at": self.finished_at,
            "status": self.status,
            "return_code": self.return_code,
            "error_message": self.error_message,
            "auth_mode": self.auth_mode,
            "principal": self.principal.to_dict(),
            "command": self.parsed_cmd.to_dict(),
            "artifact_dir": str(self.artifact_dir),
            "artifacts": self.artifacts,
            "log_line_count": len(self.logs),
        }
        if include_logs:
            payload["logs"] = self.logs
        return payload


class RunManager:
    """Manages active and completed AIPerf benchmark jobs for the Web UI."""

    def __init__(
        self,
        base_runs_dir: Path | None = None,
        auth_manager: GoogleAuthManager | None = None,
    ) -> None:
        self._base_runs_dir = base_runs_dir or (WORKSPACE_ROOT / "artifacts")
        self.auth_manager = auth_manager or GoogleAuthManager()
        self._jobs: dict[str, BenchmarkJob] = {}
        self._active_run_id: str | None = None
        self._lock = asyncio.Lock()

    @property
    def base_runs_dir(self) -> Path:
        return self._base_runs_dir

    def get_job(self, run_id: str) -> BenchmarkJob | None:
        return self._jobs.get(run_id)

    def list_jobs(self) -> list[dict[str, Any]]:
        return [
            job.to_dict(include_logs=False)
            for job in reversed(list(self._jobs.values()))
        ]

    def _allocate_run_id(self, base_name: str) -> str:
        candidate = base_name
        suffix = 2
        while candidate in self._jobs or (self._base_runs_dir / candidate).exists():
            candidate = f"{base_name}_{suffix}"
            suffix += 1
        return candidate

    async def start_run(
        self,
        *,
        raw_command: str,
        run_name: str | None = None,
        hf_token: str | None = None,
        quota_project: str | None = None,
        auth_mode: str = "direct",
    ) -> BenchmarkJob:
        if auth_mode not in ("direct", "proxy"):
            raise ValueError("auth_mode must be 'direct' or 'proxy'.")

        clean_run_name = sanitize_run_name(run_name)
        clean_hf_token = (hf_token or "").strip() or None

        async with self._lock:
            if self._active_run_id is not None:
                active = self._jobs.get(self._active_run_id)
                if active and active.status in ("starting", "running"):
                    raise RuntimeError(
                        f"Benchmark '{active.run_id}' is already running. Stop it or wait for completion."
                    )

            token_provider = await asyncio.to_thread(
                self.auth_manager.build_token_provider,
                quota_project=quota_project,
            )
            initial_token, _expiry_secs = await asyncio.to_thread(
                token_provider.get_access_token
            )

            parsed = await asyncio.to_thread(
                parse_and_validate_aiperf_command, raw_command
            )

            if clean_run_name:
                effective_run_name = clean_run_name
                run_id = self._allocate_run_id(clean_run_name)
            else:
                timestamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%d_%H%M%S")
                short_id = uuid.uuid4().hex[:6]
                run_id = self._allocate_run_id(f"run_{timestamp}_{short_id}")
                effective_run_name = run_id

            if parsed.has_explicit_artifact_dir and parsed.artifact_dir:
                artifact_dir = Path(parsed.artifact_dir)
            else:
                artifact_dir = (self._base_runs_dir / run_id).resolve()

            job = BenchmarkJob(
                run_id=run_id,
                run_name=effective_run_name,
                created_at=dt.datetime.now(dt.timezone.utc).isoformat(),
                principal=token_provider.info,
                parsed_cmd=parsed,
                auth_mode=auth_mode,
                artifact_dir=artifact_dir,
            )
            self._jobs[run_id] = job
            self._active_run_id = run_id

            asyncio.create_task(
                self._execute_job(job, token_provider, initial_token, clean_hf_token)
            )
            return job

    async def _execute_job(
        self,
        job: BenchmarkJob,
        token_provider: GoogleIdentityTokenProvider,
        initial_token: str,
        hf_token: str | None = None,
    ) -> None:
        proxy: VertexAuthProxy | None = None
        exec_tokens = list(job.parsed_cmd.tokens)
        env = os.environ.copy()
        env["PYTHONUNBUFFERED"] = "1"
        if hf_token:
            env["HF_TOKEN"] = hf_token

        secrets_list = [initial_token, hf_token]

        try:
            job.artifact_dir.mkdir(parents=True, exist_ok=True)

            if (
                job.parsed_cmd.subcommand == "profile"
                and not job.parsed_cmd.has_explicit_artifact_dir
            ):
                exec_tokens.extend(["--output-artifact-dir", str(job.artifact_dir)])

            if job.auth_mode == "proxy" and job.parsed_cmd.urls:
                proxy = VertexAuthProxy(token_provider, job.parsed_cmd.urls)
                await proxy.start()
                mapping = proxy.build_url_mapping()
                exec_tokens = rewrite_urls_in_tokens(exec_tokens, mapping)
                existing_no_proxy = env.get("NO_PROXY") or env.get("no_proxy") or ""
                no_proxy_entries = [
                    x.strip() for x in existing_no_proxy.split(",") if x.strip()
                ]
                for host in ("127.0.0.1", "localhost"):
                    if host not in no_proxy_entries:
                        no_proxy_entries.append(host)
                env["NO_PROXY"] = ",".join(no_proxy_entries)
                env["no_proxy"] = env["NO_PROXY"]
            else:
                env[ENV_BEARER_TOKEN] = initial_token
                if token_provider.quota_project:
                    env[ENV_QUOTA_PROJECT] = token_provider.quota_project

            proc = await asyncio.create_subprocess_exec(
                sys.executable,
                "-u",
                "-m",
                "vertex_aiperf.worker",
                *exec_tokens,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.STDOUT,
                cwd=str(WORKSPACE_ROOT),
                env=env,
                start_new_session=True,
                limit=1024 * 1024,
            )
            job._process = proc
            job.status = "running"
            job.broadcast_status()

            assert proc.stdout is not None
            while True:
                raw_line = await proc.stdout.readline()
                if not raw_line:
                    break
                # Preserve exact spaces and box-drawing ASCII/Unicode characters verbatim
                text_line = raw_line.decode("utf-8", errors="replace").rstrip("\r\n")
                job.append_log(text_line, secrets_to_scrub=secrets_list)

            rc = await proc.wait()
            job.return_code = rc
            job.artifacts = await asyncio.to_thread(
                list_artifact_files, job.artifact_dir
            )

            if job._stop_requested:
                job.status = "cancelled"
            elif rc == 0:
                job.status = "succeeded"
            else:
                job.status = "failed"
                job.error_message = f"AIPerf exited with status code {rc}."

        except Exception as exc:
            job.status = "failed"
            job.error_message = str(exc)
            job.append_log(
                f"Execution error: {exc}",
                secrets_to_scrub=secrets_list,
            )
        finally:
            if proxy is not None:
                await proxy.stop()
            job._process = None
            job.finished_at = dt.datetime.now(dt.timezone.utc).isoformat()
            if self._active_run_id == job.run_id:
                self._active_run_id = None
            job.broadcast_status()
            job.close_subscribers()

    async def stop_run(self, run_id: str) -> BenchmarkJob:
        job = self._jobs.get(run_id)
        if job is None:
            raise KeyError(f"Unknown run_id: {run_id}")

        proc = job._process
        if proc is None or proc.returncode is not None:
            return job

        job._stop_requested = True
        try:
            pgid = os.getpgid(proc.pid)
            os.killpg(pgid, signal.SIGINT)
        except ProcessLookupError:
            return job

        try:
            await asyncio.wait_for(proc.wait(), timeout=5.0)
            return job
        except asyncio.TimeoutError:
            pass

        try:
            os.killpg(os.getpgid(proc.pid), signal.SIGTERM)
            await asyncio.wait_for(proc.wait(), timeout=3.0)
        except (ProcessLookupError, asyncio.TimeoutError):
            try:
                os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
            except ProcessLookupError:
                pass
        return job

    def subscribe(
        self, run_id: str
    ) -> tuple[BenchmarkJob, list[str], asyncio.Queue[dict[str, Any] | None]]:
        job = self._jobs.get(run_id)
        if job is None:
            raise KeyError(f"Unknown run_id: {run_id}")
        q: asyncio.Queue[dict[str, Any] | None] = asyncio.Queue()
        existing_logs = list(job.logs)
        if job.status in ("starting", "running"):
            job._subscribers.add(q)
        else:
            q.put_nowait(None)
        return job, existing_logs, q

    def unsubscribe(
        self, run_id: str, q: asyncio.Queue[dict[str, Any] | None]
    ) -> None:
        job = self._jobs.get(run_id)
        if job is not None:
            job._subscribers.discard(q)


def _interactive_terminal_oauth(auth_manager: GoogleAuthManager) -> None:
    """Perform an interactive OAuth 2.0 PKCE login in the terminal."""
    auth_url, state = auth_manager.start_oauth_flow(
        redirect_uri=GOOGLE_SDK_AUTHCODE_REDIRECT_URI,
    )
    print(
        "\n[vertex-aiperf] Open the following URL in your browser to sign in with your Google Account:\n",
        file=sys.stderr,
    )
    print(f"  {auth_url}\n", file=sys.stderr)
    try:
        webbrowser.open(auth_url, new=1, autoraise=True)
    except Exception:
        pass
    code = input("[vertex-aiperf] Paste the authorization code from Google: ").strip()
    auth_manager.complete_oauth_flow(state=state, code=code)


async def run_cli_mode(
    *,
    raw_command: str,
    run_name: str | None = None,
    hf_token: str | None = None,
    quota_project: str | None = None,
    auth_mode: str = "direct",
    auth_manager: GoogleAuthManager | None = None,
) -> int:
    """Run AIPerf directly in the current terminal (preserving Textual TUI / TTY)."""
    mgr = auth_manager or GoogleAuthManager()
    if not mgr.get_status()["authenticated"]:
        await asyncio.to_thread(_interactive_terminal_oauth, mgr)

    token_provider = mgr.build_token_provider(
        quota_project=quota_project,
    )
    token, expiry_secs = token_provider.get_access_token()
    parsed = parse_and_validate_aiperf_command(raw_command)
    clean_run_name = sanitize_run_name(run_name)

    expiry_str = (
        f" (valid for {int(expiry_secs // 60)}m)" if expiry_secs is not None else ""
    )
    print(
        f"[vertex-aiperf] Authenticated via Google Account: "
        f"{token_provider.info.principal_email}{expiry_str}",
        file=sys.stderr,
    )
    for note in parsed.notes:
        print(f"[vertex-aiperf] Note: {note}", file=sys.stderr)

    exec_tokens = list(parsed.tokens)
    if (
        clean_run_name
        and parsed.subcommand == "profile"
        and not parsed.has_explicit_artifact_dir
    ):
        target_dir = (WORKSPACE_ROOT / "artifacts" / clean_run_name).resolve()
        exec_tokens.extend(["--output-artifact-dir", str(target_dir)])
    env = os.environ.copy()
    if hf_token and hf_token.strip():
        env["HF_TOKEN"] = hf_token.strip()
    proxy: VertexAuthProxy | None = None

    try:
        if auth_mode == "proxy" and parsed.urls:
            proxy = VertexAuthProxy(token_provider, parsed.urls)
            await proxy.start()
            exec_tokens = rewrite_urls_in_tokens(
                exec_tokens, proxy.build_url_mapping()
            )
            existing_no_proxy = env.get("NO_PROXY") or env.get("no_proxy") or ""
            no_proxy_entries = [
                x.strip() for x in existing_no_proxy.split(",") if x.strip()
            ]
            for host in ("127.0.0.1", "localhost"):
                if host not in no_proxy_entries:
                    no_proxy_entries.append(host)
            env["NO_PROXY"] = ",".join(no_proxy_entries)
            env["no_proxy"] = env["NO_PROXY"]
            print(
                f"[vertex-aiperf] Auto-refreshing Google OAuth2 proxy listening on 127.0.0.1:{proxy.port}",
                file=sys.stderr,
            )
        else:
            env[ENV_BEARER_TOKEN] = token
            if token_provider.quota_project:
                env[ENV_QUOTA_PROJECT] = token_provider.quota_project

        proc = await asyncio.create_subprocess_exec(
            sys.executable,
            "-u",
            "-m",
            "vertex_aiperf.worker",
            *exec_tokens,
            stdin=None,
            stdout=None,
            stderr=None,
            env=env,
        )
        return await proc.wait()
    finally:
        if proxy is not None:
            await proxy.stop()
